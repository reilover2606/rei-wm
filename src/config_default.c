#include "config.h"

const char *rei_config_default_text(void)
{
	return
"# rei-wm configuration\n"
"#\n"
"# This file was created on first run. Edit it by hand, or use the rei-wm\n"
"# settings application once it exists. Every value shown here is the default.\n"
"\n"
"[general]\n"
"# Which backend to run on: \"auto\", \"drm\", \"headless\" or \"nested\".\n"
"# \"drm\" drives the displays directly (run it from a text console). \"auto\"\n"
"# picks \"nested\" when started inside another Wayland session, else \"drm\".\n"
"backend = \"auto\"\n"
"\n"
"# The composition key used for window-management shortcuts:\n"
"# \"super\", \"alt\", \"ctrl\" or \"shift\".\n"
"composition_key = \"super\"\n"
"\n"
"# Whether moving the pointer onto a window focuses it (otherwise: click to focus).\n"
"focus_follows_mouse = false\n"
"\n"
"# Run Xwayland, so X11 programs work (needs the Xwayland binary installed).\n"
"xwayland = true\n"
"\n"
"[layout]\n"
"# \"tile\" puts new windows in the tiling grid; \"float\" lets them float. Dialogs\n"
"# (windows with a parent, or of fixed size) always float.\n"
"new_windows = \"tile\"\n"
"# Gaps are in pixels. gap_outer is the margin between the windows and the\n"
"# edge of the desktop; gap_inner is the space between neighbouring windows.\n"
"gap_outer = 10\n"
"gap_inner = 10\n"
"\n"
"[input]\n"
"# Keyboard layout, as xkb names (see `localectl list-x11-keymap-layouts`).\n"
"# Empty fields use the system default (or the XKB_DEFAULT_* variables).\n"
"keyboard_layout = \"\"\n"
"keyboard_variant = \"\"\n"
"keyboard_options = \"\"       # e.g. \"ctrl:nocaps\"\n"
"keyboard_model = \"\"\n"
"keyboard_rules = \"\"\n"
"# Key repeat: clients do the repeating; these are what they are told to use.\n"
"repeat_rate = 25    # per second; 0 turns repeat off\n"
"repeat_delay = 600  # milliseconds before repeating starts\n"
"# Mice and touchpads (used when running on real hardware):\n"
"tap_to_click = true\n"
"natural_scroll = false\n"
"left_handed = false\n"
"pointer_accel = 0.0   # -1.0 (slowest) to 1.0 (fastest)\n"
"\n"
"[keybindings]\n"
"# \"Mod\" is the composition key chosen above. Other modifiers: Super, Alt, Ctrl,\n"
"# Shift. Actions: exec <command>, close, quit, focus_next, focus_prev,\n"
"# focus|move left|right|up|down, split h|v, toggle_floating, fullscreen,\n"
"# workspace <n>, move_to_workspace <n>, none (removes a binding).\n"
"\"Mod+Return\" = \"exec ${TERMINAL:-foot}\"\n"
"\"Mod+Shift+q\" = \"close\"\n"
"\"Mod+Shift+e\" = \"quit\"\n"
"\"Mod+Tab\" = \"focus_next\"\n"
"\"Mod+Shift+Tab\" = \"focus_prev\"\n"
"\"Mod+h\" = \"focus left\"\n"
"\"Mod+j\" = \"focus down\"\n"
"\"Mod+k\" = \"focus up\"\n"
"\"Mod+l\" = \"focus right\"\n"
"\"Mod+Shift+h\" = \"move left\"\n"
"\"Mod+Shift+j\" = \"move down\"\n"
"\"Mod+Shift+k\" = \"move up\"\n"
"\"Mod+Shift+l\" = \"move right\"\n"
"\"Mod+b\" = \"split h\"\n"
"\"Mod+v\" = \"split v\"\n"
"\"Mod+Shift+space\" = \"toggle_floating\"\n"
"\"Mod+f\" = \"fullscreen\"\n"
"\"Mod+1\" = \"workspace 1\"\n"
"\"Mod+2\" = \"workspace 2\"\n"
"\"Mod+3\" = \"workspace 3\"\n"
"\"Mod+4\" = \"workspace 4\"\n"
"\"Mod+5\" = \"workspace 5\"\n"
"\"Mod+6\" = \"workspace 6\"\n"
"\"Mod+7\" = \"workspace 7\"\n"
"\"Mod+8\" = \"workspace 8\"\n"
"\"Mod+9\" = \"workspace 9\"\n"
"\"Mod+0\" = \"workspace 10\"\n"
"\"Mod+Shift+1\" = \"move_to_workspace 1\"\n"
"\"Mod+Shift+2\" = \"move_to_workspace 2\"\n"
"\"Mod+Shift+3\" = \"move_to_workspace 3\"\n"
"\"Mod+Shift+4\" = \"move_to_workspace 4\"\n"
"\"Mod+Shift+5\" = \"move_to_workspace 5\"\n"
"\"Mod+Shift+6\" = \"move_to_workspace 6\"\n"
"\"Mod+Shift+7\" = \"move_to_workspace 7\"\n"
"\"Mod+Shift+8\" = \"move_to_workspace 8\"\n"
"\"Mod+Shift+9\" = \"move_to_workspace 9\"\n"
"\"Mod+Shift+0\" = \"move_to_workspace 10\"\n"
"\n"
"[toolbar]\n"
"# A strip along one edge of every output: workspace buttons at its start (the\n"
"# left of a horizontal bar, the top of a vertical one) and a clock at its end.\n"
"# Windows never use the space it takes.\n"
"enabled = true\n"
"position = \"top\"        # \"top\", \"bottom\", \"left\" or \"right\"\n"
"thickness = 28            # pixels\n"
"font = \"Sans 11\"        # a Pango font description\n"
"clock_format = \"%H:%M\"  # strftime format; empty for no clock\n"
"background = \"#161c26\"\n"
"foreground = \"#d6dde8\"\n"
"highlight = \"#3c6ebe\"   # the workspace you are on\n"
"\n"
"[decoration]\n"
"# Windows have no border. The focused one shows two small tabs hovering above its\n"
"# top edge: a drag handle on the left, and minimize/maximize/close on the right.\n"
"# This is their height in pixels (0 turns them off). Tiled windows always keep at\n"
"# least this much room above them, and floating windows can't be dragged higher\n"
"# than this from the top of the screen, so the tabs never go off it.\n"
"notch_height = 22\n"
"\n"
"[wallpaper]\n"
"# An image to draw behind everything (PNG, JPEG, BMP, TGA or PNM). Empty means\n"
"# no image, only the background colour. \"~/\" refers to your home directory.\n"
"path = \"\"\n"
"# How the image fits an output: \"fill\" (cover, cropping), \"fit\" (contain),\n"
"# \"stretch\", \"center\" or \"tile\".\n"
"mode = \"fill\"\n"
"# Shown where the image doesn't reach, and when there is no image.\n"
"color = \"#1b2733\"\n"
"\n"
"# Describe monitors with one [[output]] table each. They are placed left to\n"
"# right in the order listed unless x/y are given. With the drm backend the\n"
"# name is the connector (see `rei-wm --drm-info`: DP-1, HDMI-A-1, eDP-1, ...)\n"
"# and monitors you don't list are used at their preferred mode. With the\n"
"# headless and nested backends, none listed means one 1920x1080 output.\n"
"#\n"
"# [[output]]\n"
"# name = \"DP-1\"\n"
"# mode = \"2560x1440@144\"   # or width / height / refresh = 60.0 (Hz)\n"
"# enabled = true           # false leaves the monitor off\n"
"# scale = 1.0\n"
"# x = 0            # optional; give both x and y to pin the position\n"
"# y = 0\n";
}
