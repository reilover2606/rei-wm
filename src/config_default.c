#include "config.h"

const char *rei_config_default_text(void)
{
	return
"# rei-wm configuration\n"
"#\n"
"# This file was created on first run. Edit it by hand, or use the rei-wm\n"
"# settings application once it exists. Every value shown here is the default.\n"
"\n"
"[general]\n"
"# Which backend to run on: \"auto\", \"drm\", \"headless\" or \"nested\".\n"
"# \"drm\" drives the displays directly (run it from a text console). \"auto\"\n"
"# picks \"nested\" when started inside another Wayland session, else \"drm\".\n"
"backend = \"auto\"\n"
"\n"
"# The composition key used for window-management shortcuts:\n"
"# \"super\", \"alt\", \"ctrl\" or \"shift\".\n"
"composition_key = \"super\"\n"
"\n"
"# Focus follows the pointer: hovering a window focuses it, and leaving every window focuses nothing.\n# Set to false for click-to-focus.\n"
"focus_follows_mouse = true\n"
"\n# \"inherit\" (default): programs started from rei-wm use the D-Bus session bus you already have.\n"
"# Single-instance GTK/GNOME programs may then open their window in ANOTHER running desktop of yours.\n"
"# \"private\": rei-wm starts its own session bus for the programs it launches, so they open here\n"
"# (portals, notifications and the keyring of the other desktop are then not available to them).\n"
"session_bus = \"inherit\"\n"
"\n"
"# Run Xwayland, so X11 programs work (needs the Xwayland binary installed).\n"
"xwayland = true\n"
"\n# X resources (colours, fonts, urxvt/xterm transparency, ...) loaded into Xwayland with `xrdb -merge`\n"
"# when it starts, as an X session's startup script would. \"\" turns it off. Needs xrdb installed.\n"
"xresources = \"~/.Xresources\"\n"
"\n"
"[cursor]\n"
"# The pointer: an XCursor theme (a folder with a cursors/ directory in ~/.local/share/icons, ~/.icons,\n"
"# /usr/share/icons, /usr/share/cursors, ...) and its size in pixels. \"\" = the system's default theme\n"
"# ($XCURSOR_THEME, then \"default\"). `rei-wm --list-cursor-themes` lists what is installed. The shape follows\n"
"# what is under the pointer: text, link, resize edges, ... (programs choose theirs; rei-wm's own widgets too).\n"
"theme = \"\"\n"
"size = 24\n"
"\n"
"[layout]\n"
"# \"tile\" puts new windows in the tiling grid; \"float\" lets them float. Dialogs\n"
"# (windows with a parent, or of fixed size) always float.\n"
"new_windows = \"tile\"\n"
"# Gaps are in pixels. gap_outer is the margin between the windows and the\n"
"# edge of the desktop; gap_inner is the space between neighbouring windows.\n"
"gap_outer = 10\n"
"gap_inner = 10\n"
"\n"
"[input]\n"
"# Keyboard layout, as xkb names (see `localectl list-x11-keymap-layouts`).\n"
"# Empty fields use the system default (or the XKB_DEFAULT_* variables).\n"
"keyboard_layout = \"\"\n"
"keyboard_variant = \"\"\n"
"keyboard_options = \"\"       # e.g. \"ctrl:nocaps\"\n"
"keyboard_model = \"\"\n"
"keyboard_rules = \"\"\n"
"# Key repeat: clients do the repeating; these are what they are told to use.\n"
"repeat_rate = 25    # per second; 0 turns repeat off\n"
"repeat_delay = 600  # milliseconds before repeating starts\n"
"# Mice and touchpads (used when running on real hardware):\n"
"tap_to_click = true\n"
"natural_scroll = false\n"
"left_handed = false\n"
"pointer_accel = 0.0   # -1.0 (slowest) to 1.0 (fastest)\n"
"\n"
"[keybindings]\n"
"# \"Mod\" is the composition key chosen above. Other modifiers: Super, Alt, Ctrl,\n"
"# Shift. Actions: exec <command>, close, quit, focus_next, focus_prev,\n"
"# focus|move left|right|up|down, split h|v, toggle_floating, fullscreen, minimize, run, messages,\n"
"# workspace <n>, move_to_workspace <n>, volume_up|volume_down [percent],\n"
"# volume_mute, none (removes a binding).\n"
"\"Mod+Return\" = \"exec ${TERMINAL:-foot}\"\n"
"\"Mod+Shift+q\" = \"close\"\n"
"\"Mod+Shift+e\" = \"quit\"\n"
"\"Mod+Tab\" = \"focus_next\"\n"
"\"Mod+Shift+Tab\" = \"focus_prev\"\n"
"\"Mod+h\" = \"focus left\"\n"
"\"Mod+j\" = \"focus down\"\n"
"\"Mod+k\" = \"focus up\"\n"
"\"Mod+l\" = \"focus right\"\n"
"\"Mod+Shift+h\" = \"move left\"\n"
"\"Mod+Shift+j\" = \"move down\"\n"
"\"Mod+Shift+k\" = \"move up\"\n"
"\"Mod+Shift+l\" = \"move right\"\n"
"\"Mod+b\" = \"split h\"\n"
"\"Mod+v\" = \"split v\"\n"
"\"Mod+Shift+space\" = \"toggle_floating\"\n"
"\"Mod+f\" = \"fullscreen\"\n"
"\"Mod+m\" = \"minimize\"\n"
"\"Mod+r\" = \"run\"\n"
"\"Mod+n\" = \"messages\"\n"
"\"Mod+1\" = \"workspace 1\"\n"
"\"Mod+2\" = \"workspace 2\"\n"
"\"Mod+3\" = \"workspace 3\"\n"
"\"Mod+4\" = \"workspace 4\"\n"
"\"Mod+5\" = \"workspace 5\"\n"
"\"Mod+6\" = \"workspace 6\"\n"
"\"Mod+7\" = \"workspace 7\"\n"
"\"Mod+8\" = \"workspace 8\"\n"
"\"Mod+9\" = \"workspace 9\"\n"
"\"Mod+0\" = \"workspace 10\"\n"
"\"Mod+Shift+1\" = \"move_to_workspace 1\"\n"
"\"Mod+Shift+2\" = \"move_to_workspace 2\"\n"
"\"Mod+Shift+3\" = \"move_to_workspace 3\"\n"
"\"Mod+Shift+4\" = \"move_to_workspace 4\"\n"
"\"Mod+Shift+5\" = \"move_to_workspace 5\"\n"
"\"Mod+Shift+6\" = \"move_to_workspace 6\"\n"
"\"Mod+Shift+7\" = \"move_to_workspace 7\"\n"
"\"Mod+Shift+8\" = \"move_to_workspace 8\"\n"
"\"Mod+Shift+9\" = \"move_to_workspace 9\"\n"
"\"Mod+Shift+0\" = \"move_to_workspace 10\"\n"
"# Media keys: volume_up / volume_down take an optional step in percent.\n"
"\"XF86AudioRaiseVolume\" = \"volume_up\"\n"
"\"XF86AudioLowerVolume\" = \"volume_down\"\n"
"\"XF86AudioMute\" = \"volume_mute\"\n"
"\n"
"[messages]\n"
"# Text messages from rei-wm (for now: the output of what you ran from the Run prompt) in an invisible\n"
"# column at the edge of the screen. A new message is shown for `duration` seconds, fading near the\n"
"# end; each newer one pushes the older ones up and dims them a step. Mod+n shows the whole stack\n"
"# (scroll with the mouse wheel; Mod+n or Escape closes it).\n"
"enabled = true\n"
"position = \"right\"      # or \"left\"\n"
"duration = 10.0         # seconds\n"
"max_visible = 6         # messages shown at once outside the stack view\n"
"width = 480             # pixels\n"
"history = 200           # messages kept for the stack view\n"
"font = \"Sans 12\"\n"
"# Mod+n is a top layer: everything under it is blurred and darkened, and nothing reaches the windows.\n"
"blur_radius = 12        # pixels; 0 = no blur\n"
"blur_dim = 0.3          # how much darker the blurred screen is, 0 to 0.9\n"
"\n"
"[mpd]\n"
"# Music controls (play, pause, skip, and the song) at the bottom centre of the Mod+n view, and\n"
"# \"Now playing: ...\" in the messages when the song changes. With MPD not running, a button starts it.\n"
"enabled = true\n"
"host = \"\"             # \"\" = $MPD_HOST, else $XDG_RUNTIME_DIR/mpd/socket, else localhost;\n"
"                        # an IP address, localhost or a socket path (\"password@host\" for a password)\n"
"port = 6600\n"
"start_command = \"mpd\"  # what the \"Start MPD\" button runs\n"
"announce = true         # announce a new song in the messages\n"
"\n"
"[start_menu]\n"
"# A Start button at the left end of the toolbar. Its menu has your shortcuts (below), then \"Run\"\n"
"# (a large floating command prompt in the middle of the screen), then Logout / Shutdown / Reboot.\n"
"enabled = true\n"
"label = \"Start\"\n"
"# Ask for a second click before logging out, shutting down or rebooting.\n"
"confirm_power = true\n"
"shutdown_command = \"loginctl poweroff || systemctl poweroff || poweroff\"\n"
"reboot_command = \"loginctl reboot || systemctl reboot || reboot\"\n"
"# Empty: Logout simply ends rei-wm and returns to the console.\n"
"logout_command = \"\"\n"
"run_font = \"Sans 26\"      # the Run prompt's font; it is meant to be large\n"
"\n"
"# Shortcuts shown at the top of the Start menu, one [[shortcut]] table each (at most 20):\n"
"#\n"
"# [[shortcut]]\n"
"# name = \"Firefox\"\n"
"# command = \"firefox\"\n"
"#\n"
"# [[shortcut]]\n"
"# name = \"Files\"\n"
"# command = \"thunar\"\n"
"\n"
"[audio]\n"
"# The volume shown in the toolbar and changed by the media keys (needs PipeWire).\n"
"enabled = true\n"
"# Start the sound system if it is not already running: pipewire (if its socket is missing),\n"
"# wireplumber (the session manager that creates the sound devices; without it there is no volume\n"
"# widget) and pipewire-pulse (for programs that speak PulseAudio, such as Firefox). Programs\n"
"# rei-wm started are stopped when it exits; anything already running is left alone.\n"
"autostart = true\n"
"volume_step = 5     # percent per key press or wheel notch\n"
"max_volume = 100    # percent; above 100 amplifies and may distort\n"
"\n"
"[toolbar]\n"
"# A strip along one edge of every output: workspace buttons at its start (the\n"
"# left of a horizontal bar, the top of a vertical one) and a clock at its end.\n"
"# Windows never use the space it takes.\n"
"enabled = true\n"
"position = \"top\"        # \"top\", \"bottom\", \"left\" or \"right\"\n"
"thickness = 28            # pixels\n"
"font = \"Sans 11\"        # a Pango font description\n"
"# The application tray in the middle of the bar lists every open window, one tile per\n"
"# application (a stack of tiles when it has several windows). Click a tile to bring the\n"
"# window forward, to hide it again, or to pick one from a list. \"icon_and_name\", \"icon\" or \"off\".\n"
"tray = \"icon_and_name\"\n"
"# Whose windows the tray lists: \"workspace\" (the one this monitor shows) or \"output\" (all of\n"
"# this monitor's workspaces). In the middle three fifths of the bar, tiles shrink as it fills, down\n"
"# to tray_min_width percent of their size; after that the newest windows go under a \"+N\" tile.\n"
"# With scope \"workspace\", once 32 windows are under it, new windows open on the next workspace.\n"
"tray_scope = \"workspace\"\n"
"# A battery icon and percentage before the volume and clock. It appears only if the machine has a\n"
"# battery; several are combined into one.\n"
"battery = true\n"
"\n# CPU and RAM use in one box, just left of the clock (updated every two seconds).\n"
"sysinfo = true\n"
"tray_min_width = 50\n"
"# The clock at the end of the bar. Any strftime format: \"%H:%M:%S\" (24 h with seconds),\n"
"# \"%H:%M\", \"%I:%M %p\" (12 h), \"%a %d %b  %H:%M\"; empty for no clock.\n"
"clock_format = \"%H:%M:%S\"\n"
"background = \"#161c26\"\n"
"foreground = \"#d6dde8\"\n"
"highlight = \"#3c6ebe\"   # the workspace you are on\n"
"\n"
"[decoration]\n"
"# Windows have no border. The focused one shows two small tabs hovering above its\n"
"# top edge: a drag handle on the left, and minimize/maximize/close on the right.\n"
"# This is their height in pixels (0 turns them off). Tiled windows always keep at\n"
"# least this much room above them, and floating windows can't be dragged higher\n"
"# than this from the top of the screen, so the tabs never go off it.\n"
"notch_height = 22\n"
"\n"
"[wallpaper]\n"
"# An image to draw behind everything (PNG, JPEG, BMP, TGA or PNM). Empty means\n"
"# no image, only the background colour. \"~/\" refers to your home directory.\n"
"path = \"\"\n"
"# How the image fits an output: \"fill\" (cover, cropping), \"fit\" (contain),\n"
"# \"stretch\", \"center\" or \"tile\".\n"
"mode = \"fill\"\n"
"# Shown where the image doesn't reach, and when there is no image.\n"
"color = \"#1b2733\"\n"
"\n"
"# Describe monitors with one [[output]] table each. They are placed left to\n"
"# right in the order listed unless x/y are given. With the drm backend the\n"
"# name is the connector (see `rei-wm --drm-info`: DP-1, HDMI-A-1, eDP-1, ...)\n"
"# and monitors you don't list are used at their preferred mode. A table with no name\n"
"# applies to every monitor that is not named. With the\n"
"# headless and nested backends, none listed means one 1920x1080 output.\n"
"#\n"
"# [[output]]\n"
"# name = \"DP-1\"\n"
"# mode = \"2560x1440@144\"   # or width / height / refresh = 60.0 (Hz)\n"
"# enabled = true           # false leaves the monitor off\n"
"# scale = 1.0\n"
"# x = 0            # optional; give both x and y to pin the position\n"
"# y = 0\n";
}
